def review_checklist() -> str:
    """Checklist for reviewing business requirements."""
    return """
BA Review Checklist:
--------------------
☐ Completeness  — Are all stakeholder needs captured?
☐ Traceability  — Can each requirement be traced to a business goal?
☐ Clarity       — Is the language unambiguous and jargon-free?
☐ Testability   — Can each requirement be objectively verified?
☐ Consistency   — Are there any conflicting requirements?
☐ Feasibility   — Is the requirement technically and financially viable?
☐ Priority      — Has a MoSCoW or similar prioritisation been applied?
"""